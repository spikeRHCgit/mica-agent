@pytest.mark.parametrize(
    "command",
    [
        "echo hello",
        "printf '%s' 'rm -rf /'",
        "echo '$(rm x)'",
        "echo '`rm x`'",
        'echo "rm x; sudo x"',
        "echo rm",
        "echo .env",
        "printf '%s' '.env'",
        "echo hello\\ world",
        "echo ok; pwd",
        "echo ok\npwd",
        "echo ok && pwd || echo no",
        "printf hello | cat",
        "env X=1 command echo hi",
        "env -i python script.py",
        "git status",
        "git diff",
        "git log",
        "git show",
        "git add .",
        "git commit -m 'fix'",
        "git branch -d old",
        "git --no-pager diff",
        "git reset --soft HEAD",
        "curl https://example.test",
        "wget https://example.test/file",
        "python script.py",
        "python -m pytest",
        "uv run pytest",
        "bash script.sh",
        "unknown-program arg",
        '"/some path/program.exe" arg',
        "curl https://example.test -o output.txt",
        "curl https://example.test -ooutput.txt",
        "curl https://example.test --output output.txt",
        "curl https://example.test --output=output.txt",
        "echo x > output.txt",
    ],
)
def test_no_match_is_not_a_safety_proof(command: str) -> None:
    result = analyze_command(command)
    assert result.risk is CommandRisk.NO_MATCH
    assert not result.requires_confirmation
