"""Semantic main-buffer document and differential frame rendering.

The renderer retains unwrapped semantic blocks, or block-owned physical rows, and lays
them out at the current terminal width so resize can reflow them. Screen content has a
permanent document that naturally enters scrollback, a recent redraw region with one
mutable tail block, and bottom chrome for status, composer, and facts.

A retained screen map gives every physical row a stable identity: stream plus logical
row, with stream ``-1`` reserved for chrome. Repaint compares identity and text, moves
only to the first changed row, erases below it, and writes the changed suffix. Ordinary
deltas redraw only their tail; earlier height changes reflow from a controlled origin;
cursor-only changes send relative positioning without body output or erasure; and the
first frame writes downward without touching pre-existing shell content. The map never
exceeds terminal height, so every tracked row remains addressable on screen.

The renderer never enters the alternate screen, captures the mouse, clears scrollback,
or sets a window title. Block text is untrusted and sanitized before layout; blocks with
ANSI may contain only trusted style sequences generated by renderer components.
"""

